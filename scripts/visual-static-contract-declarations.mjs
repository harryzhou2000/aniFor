import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { readFile, rename, unlink, writeFile } from 'node:fs/promises';

import { VISUAL_LAB_STATIC_CONTRACT } from '../src/shared/visual-lab-static-contract.js';
import { VISUAL_CAPTURE_STATIC_CONTRACT } from '../src/shared/visual-capture-static-contract.js';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = dirname(SCRIPT_DIR);

const indent = (depth) => '  '.repeat(depth);

const renderLiteralType = (value, depth = 0) => {
  if (value === null) return 'null';
  if (typeof value === 'string') return JSON.stringify(value);
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return 'readonly []';
    const entries = value.map((entry) => (
      `${indent(depth + 1)}${renderLiteralType(entry, depth + 1)},`
    ));
    return `readonly [\n${entries.join('\n')}\n${indent(depth)}]`;
  }
  if (typeof value === 'object') {
    const entries = Object.entries(value);
    if (entries.length === 0) return 'Readonly<Record<string, never>>';
    const fields = entries.map(([key, entry]) => (
      `${indent(depth + 1)}readonly ${JSON.stringify(key)}: ${renderLiteralType(entry, depth + 1)};`
    ));
    return `Readonly<{\n${fields.join('\n')}\n${indent(depth)}}>`;
  }
  throw new TypeError(`unsupported static-contract value type ${typeof value}`);
};

export const renderVisualStaticContractDeclarations = () => Object.freeze({
  visualLab: [
    '// Generated by scripts/visual-static-contract-declarations.mjs. Do not edit.',
    `export declare const VISUAL_LAB_STATIC_CONTRACT: ${renderLiteralType(VISUAL_LAB_STATIC_CONTRACT)};`,
    '',
  ].join('\n'),
  visualCapture: [
    '// Generated by scripts/visual-static-contract-declarations.mjs. Do not edit.',
    `export declare const VISUAL_CAPTURE_STATIC_CONTRACT: ${renderLiteralType(VISUAL_CAPTURE_STATIC_CONTRACT)};`,
    '',
    'export type VisualCaptureEvidencePlane = (',
    '  typeof VISUAL_CAPTURE_STATIC_CONTRACT.evidencePlanes[number]',
    ');',
    '',
  ].join('\n'),
});

export const VISUAL_STATIC_DECLARATION_TARGETS = Object.freeze([
  Object.freeze({
    name: 'visualLab',
    path: join(ROOT_DIR, 'src/shared/visual-lab-static-contract.d.ts'),
  }),
  Object.freeze({
    name: 'visualCapture',
    path: join(ROOT_DIR, 'src/shared/visual-capture-static-contract.d.ts'),
  }),
]);

export const checkVisualStaticContractDeclarations = async (
  targets = VISUAL_STATIC_DECLARATION_TARGETS,
  declarations = renderVisualStaticContractDeclarations(),
) => {
  const stale = [];
  for (const target of targets) {
    let actual;
    try {
      actual = await readFile(target.path, 'utf8');
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error;
      actual = null;
    }
    if (actual !== declarations[target.name]) stale.push(target.path);
  }
  return Object.freeze(stale);
};

export const syncVisualStaticContractDeclarations = async (
  targets = VISUAL_STATIC_DECLARATION_TARGETS,
  declarations = renderVisualStaticContractDeclarations(),
) => {
  for (const target of targets) {
    const temporary = `${target.path}.tmp-${process.pid}-${target.name}`;
    try {
      await writeFile(temporary, declarations[target.name], { encoding: 'utf8', flag: 'wx' });
      await rename(temporary, target.path);
    } catch (error) {
      await unlink(temporary).catch(() => {});
      throw error;
    }
  }
};

const runCli = async () => {
  const mode = process.argv[2] ?? '--check';
  if (!['--check', '--sync'].includes(mode) || process.argv.length !== 3) {
    throw new TypeError('usage: node scripts/visual-static-contract-declarations.mjs [--check|--sync]');
  }
  if (mode === '--sync') await syncVisualStaticContractDeclarations();
  const stale = await checkVisualStaticContractDeclarations();
  if (stale.length > 0) {
    throw new Error(`stale generated declarations:\n${stale.map((path) => `  ${path}`).join('\n')}`);
  }
  process.stdout.write(`visual static-contract declarations ${mode === '--sync' ? 'synchronized' : 'are current'}\n`);
};

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  runCli().catch((error) => {
    process.stderr.write(`${error.stack ?? error}\n`);
    process.exitCode = 1;
  });
}
